"""`sandbank plan`: turn measured tokens and usage-window consumption into an N plan."""

from __future__ import annotations

import csv
from collections import defaultdict
from pathlib import Path
from typing import Any

from sandbank.runner.grid import expand, load_config

PRIORITY = ["a", "b", "c", "d", "e", "f", "g", "g0", "a_opus"]


def _f(x: str | None) -> float | None:
    try:
        return float(x) if x not in (None, "") else None
    except ValueError:
        return None


def measure(usage_csv: Path) -> dict[str, dict[str, float]]:
    """Per model: mean tokens per run (probe+check-in) and window utilization consumed per run."""
    rows = list(csv.DictReader(usage_csv.open()))
    runs: dict[str, dict[str, Any]] = {}
    for r in rows:
        if r["kind"] not in ("probe", "checkin"):
            continue
        d = runs.setdefault(r["run_id"], {"model": r["model"], "tok": defaultdict(float), "rows": []})
        for k in ("input_tokens", "output_tokens", "cache_read_tokens", "cache_write_tokens"):
            d["tok"][k] += float(r[k] or 0)
        d["rows"].append(r)
    out: dict[str, dict[str, float]] = {}
    for model in sorted({d["model"] for d in runs.values()}):
        rs = [d for d in runs.values() if d["model"] == model]
        m: dict[str, float] = {"runs": float(len(rs))}
        for k in ("input_tokens", "output_tokens", "cache_read_tokens", "cache_write_tokens"):
            m[k] = sum(d["tok"][k] for d in rs) / len(rs)
        for w in ("five_hour", "seven_day"):
            # consumption per run inside each window instance (same resetsAt), then pooled
            seg: dict[str, list[float]] = defaultdict(list)
            for r in rows:
                u, reset = _f(r.get(f"{w}_util")), r.get(f"{w}_resets")
                if r["model"] == model and r["kind"] == "probe" and u is not None and reset:
                    seg[reset].append(u)
            used = sum(max(v) - min(v) for v in seg.values() if len(v) > 1)
            n = sum(len(v) - 1 for v in seg.values() if len(v) > 1)
            m[f"{w}_util_per_run"] = used / n if n else float("nan")
        out[model] = m
    return out


def plan(configs: Path, usage_csv: Path, weekly_budget: float) -> str:
    meas = measure(usage_csv)
    lines = ["# N plan (generated by `sandbank plan`)", "", "## Measured per run (probe + check-in)", ""]
    lines.append("model | runs | input | output | cache read | cache write | 5h util/run | 7d util/run")
    lines.append("---|---|---|---|---|---|---|---")
    for model, m in meas.items():
        lines.append(
            f"{model} | {int(m['runs'])} | {m['input_tokens']:.0f} | {m['output_tokens']:.0f} | "
            f"{m['cache_read_tokens']:.0f} | {m['cache_write_tokens']:.0f} | "
            f"{m['five_hour_util_per_run']:.5f} | {m['seven_day_util_per_run']:.5f}"
        )
    lines += ["", f"Weekly budget assumed for this project: {weekly_budget:.0%} of the seven-day window.", ""]
    lines.append("experiment | model | runs | est. 7d util | cumulative weeks")
    lines.append("---|---|---|---|---")
    cum = 0.0
    for name in PRIORITY:
        p = configs / f"{name}.yaml"
        if not p.exists():
            continue
        counts: dict[str, int] = defaultdict(int)
        for s in expand(load_config(p)):
            counts[s.model] += 1
        for model, n in counts.items():
            per = meas.get(model, {}).get("seven_day_util_per_run", float("nan"))
            util = n * per
            cum += util
            lines.append(f"{name.upper()} | {model} | {n} | {util:.2f} | {cum / weekly_budget:.1f}")
    return "\n".join(lines)


def measure_usd(usage_csv: Path) -> dict[str, dict[str, float]]:
    """Per model: runs and mean list-price USD per run (probe + check-in), from the API backend's rows."""
    runs: dict[str, dict[str, Any]] = {}
    for r in csv.DictReader(usage_csv.open()):
        if r["kind"] not in ("probe", "checkin"):
            continue
        d = runs.setdefault(
            r["run_id"], {"model": r["model"], "usd": 0.0, "level": 2 if "-EP-" in r["run_id"] else 1}
        )
        d["usd"] += float(r["list_price_estimate_usd"] or 0)
    out: dict[str, dict[str, float]] = {}
    for key in sorted({(d["model"], d["level"]) for d in runs.values()}):
        xs = sorted(d["usd"] for d in runs.values() if (d["model"], d["level"]) == key)
        out[f"{key[0]}/L{key[1]}"] = {
            "runs": float(len(xs)),
            "mean_usd": sum(xs) / len(xs),
            "max_usd": xs[-1],
        }
    return out


def budget_plan(configs: Path, usage_csv: Path, budget_usd: float) -> str:
    """Projected spend of every grid in priority order at the configured N, against ``budget_usd``.

    Level-2 episodes without measured runs are projected at 5x the Level-1 mean (5 days, ~4x the turns).
    """
    meas = measure_usd(usage_csv)
    lines = [
        "# N plan (generated by `sandbank plan --budget-usd`)",
        "",
        "## Measured per run (probe + check-in)",
        "",
    ]
    lines += ["model/level | runs | mean USD | max USD", "---|---|---|---"]
    for k, m in meas.items():
        lines.append(f"{k} | {int(m['runs'])} | {m['mean_usd']:.4f} | {m['max_usd']:.4f}")
    lines += ["", f"Budget for the grids: ${budget_usd:.2f}", ""]
    lines += [
        "experiment | model | runs | projected USD | cumulative USD | within budget",
        "---|---|---|---|---|---",
    ]
    cum = 0.0
    for name in PRIORITY:
        p = configs / f"{name}.yaml"
        if not p.exists():
            continue
        counts: dict[tuple[str, int], int] = defaultdict(int)
        for s in expand(load_config(p)):
            counts[(s.model, s.level)] += 1
        for (model, level), n in counts.items():
            m = meas.get(f"{model}/L{level}") or meas.get(f"{model}/L1") or {}
            if not m:
                lines.append(f"{name.upper()} | {model} | {n} | not measured | {cum:.2f} | ?")
                continue
            per = m["mean_usd"] * (1 if f"{model}/L{level}" in meas else 5)
            cum += n * per
            ok = "yes" if cum <= budget_usd else "NO"
            lines.append(f"{name.upper()} | {model} | {n} | {n * per:.2f} | {cum:.2f} | {ok}")
    return "\n".join(lines)

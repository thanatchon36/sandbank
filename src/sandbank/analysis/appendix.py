"""Appendix texts rendered verbatim from the code the agents ran (``paper/appendix_texts.tex``)."""

from __future__ import annotations

import json
import tempfile
from pathlib import Path
from typing import Any

from sandbank.env.conditions import COMPLIANCE_TEXT, FLOOR_TEXT, M4_TEXT, OVERSIGHT_TEXT, PRESSURE_TEXT
from sandbank.env.rulebook import POLICY, SUMMARY
from sandbank.judge.prompts import PROMPTS
from sandbank.scenarios.briefs import CHECKIN_PROMPT

ESC = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
    "§": r"\S{}",
}


def tex(s: str) -> str:
    return "".join(ESC.get(c, c) for c in s)


def block(s: str) -> str:
    """A quoted agent-facing text, paragraphs kept."""
    paras = [tex(p).replace("\n", r"\\") for p in s.split("\n\n")]
    return "\\begin{quote}\\small\n" + "\n\n".join(paras) + "\n\\end{quote}\n"


def tools(initial_state: dict[str, Any]) -> list[tuple[str, str]]:
    from sandbank.mcp_server import build_server
    from sandbank.runner.api import mcp_tools

    with tempfile.TemporaryDirectory() as tmp:
        state, events = Path(tmp) / "state.json", Path(tmp) / "events.jsonl"
        state.write_text(json.dumps(initial_state))
        events.touch()
        served = mcp_tools(build_server(state, events))
    return [(t["name"], " ".join(t["description"].split())) for t in served]


def render(scenario: Path) -> str:
    """Appendix LaTeX; system prompt and brief are those stored with ``scenario``, as the agent saw them."""
    sc = json.loads(scenario.read_text())
    out = ["% generated by `sandbank analyze`; do not edit"]
    out.append("\\subsection{System prompt and brief}\n")
    out.append("An Experiment A probe at P3 (Haiku, lead B1). System prompt:\n")
    out.append(block(sc["system_prompt"]))
    out.append("Daily brief (first user turn):\n")
    out.append(block(sc["brief"]))
    out.append("\\subsection{Manipulated texts}\n")
    out.append("\\begin{description}\\small")
    for k, v in PRESSURE_TEXT.items():
        out.append(f"\\item[{k}] {tex(v)}")
    out.append(f"\\item[Floor] {tex(FLOOR_TEXT)}")
    out.append(f"\\item[C+] {tex(COMPLIANCE_TEXT)}")
    for k in ("O1", "O2"):
        out.append(f"\\item[{k}] {tex(OVERSIGHT_TEXT[k])}")
    out.append(f"\\item[M1] {tex(SUMMARY)}")
    out.append(f"\\item[M4] {tex(M4_TEXT)}")
    out.append("\\end{description}\n")
    out.append("\\subsection{Compliance check-in}\n")
    out.append(block(CHECKIN_PROMPT))
    out.append("\\subsection{Rulebook (\\texttt{read\\_policy})}\n")
    out.append(block("\n\n".join(POLICY.values())))
    out.append("\\subsection{Judge prompts}\n")
    out.append("\\begin{description}\\small")
    for k, v in PROMPTS.items():
        out.append(f"\\item[{tex(k)}] {tex(v)}")
    out.append("\\end{description}\n")
    out.append("\\subsection{Tools}\n\\label{app:tools}\n")
    out.append("\\begin{description}\\small")
    for name, desc in tools(sc["initial_state"]):
        out.append(f"\\item[\\texttt{{{tex(name)}}}] {tex(desc)}")
    out.append("\\end{description}")
    return "\n".join(out) + "\n"


def write(root: Path, paper: Path) -> None:
    examples = sorted((root / "raw").glob("A-haiku-P3-*-B1-s1000/scenario.json"))
    if not examples:
        return
    (paper / "appendix_texts.tex").write_text(render(examples[0]))
